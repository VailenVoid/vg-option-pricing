def _synthetic_chain(params=TRUE, spot=100.0, r=0.03, q=0.015):
    """A clean option chain generated by the model itself."""
    rows = []
    for T in [0.08, 0.25, 0.5, 1.0]:
        fwd = spot * np.exp((r - q) * T)
        strikes = np.round(fwd * np.linspace(0.85, 1.15, 13), 2)
        prices = np.asarray(vg_call_esscher_fourier(spot, strikes, r, T, params, q))
        for k, price in zip(strikes, prices):
            iv = implied_vol(float(price), spot, float(k), r, T, q)
            rows.append(
                {
                    "expiry": f"T{T}",
                    "T": T,
                    "strike": float(k),
                    "spot": spot,
                    "r": r,
                    "q": q,
                    "price": float(price),
                    "iv": iv,
                }
            )
    return pd.DataFrame(rows).dropna(subset=["iv"])


def test_esscher_calibration_recovers_the_risk_neutral_parameters():
    """Synthetic chain in, generating *risk-neutral* parameters out.

    What can be recovered is (sigma_Q, nu), not the physical (theta, sigma, nu):
    the martingale condition makes theta unidentifiable under this
    specification, so asking the calibration to return the physical theta that
    happened to generate the chain would be asking for something the prices do
    not contain.  What must hold is that the fitted measure reprices the chain
    and agrees with the generating one on the parameters that are observable.
    """
    from vg.esscher import risk_neutral_params as rn

    chain = _synthetic_chain()
    res = calibrate(chain, "esscher")

    assert res.free_parameters == ("sigma", "nu")
    true_q = rn(TRUE, 0.03 - 0.015)[0]
    fitted_q = res.risk_neutral_params(0.03 - 0.015)

    assert fitted_q.sigma == pytest.approx(true_q.sigma, rel=0.02)
    assert fitted_q.theta == pytest.approx(true_q.theta, rel=0.05, abs=1e-4)
    assert res.params.nu == pytest.approx(TRUE.nu, rel=0.10)
    assert res.rmse_iv < 1e-4          # under 1 basis point of vol
    assert res.rmse_price < 1e-3


def test_calibration_diagnostics_are_populated():
    res = calibrate(_synthetic_chain(), "esscher")
    q = res.quotes
    for col in ["model_price", "price_error", "model_iv", "iv_error"]:
        assert col in q.columns
    assert np.isfinite(q["model_iv"]).all()
    assert len(q) == res.n_quotes


def test_price_quotes_matches_row_by_row_pricing():
    """Grouping quotes by expiry must not change any price.

    Tolerance is 5e-6 rather than machine epsilon because the shared quadrature
    grid is sized by the widest log-moneyness in the group, so the shortest
    expiry (T/nu = 0.32 here, the heavy-tailed regime) resolves slightly
    differently than it would alone.  Measured, that difference is about 1e-6
    for T/nu = 0.32 and below 1e-10 for every other expiry -- four orders of
    magnitude under the bid-ask spread of any real quote, and inside the error
    the quadrature itself reports.
    """
    chain = _synthetic_chain()
    grouped = price_quotes(chain, TRUE, "esscher")
    one_by_one = np.array(
        [
            vg_call_esscher_fourier(
                float(row.spot), float(row.strike), float(row.r), float(row["T"]), TRUE, float(row.q)
            )
            for _, row in chain.iterrows()
        ]
    )
    assert np.abs(grouped - one_by_one).max() < 5e-6


def test_calibration_rejects_a_tiny_chain():
    with pytest.raises(ValueError, match="at least 5 quotes"):
        calibrate(_synthetic_chain().head(3), "esscher")


def test_unknown_measure_is_rejected():
    with pytest.raises(ValueError, match="unknown measure"):
        price_quotes(_synthetic_chain(), TRUE, "nonsense")
