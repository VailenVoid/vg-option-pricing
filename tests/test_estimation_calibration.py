"""End-to-end recovery tests: can we get the parameters back out?

These are the tests that matter most for the empirical part of the paper.  If
the estimator cannot recover known parameters from synthetic data, nothing it
says about SPY means anything.
"""

import numpy as np
import pandas as pd
import pytest

from vg import VGParams, implied_vol, vg_call_esscher_fourier
from vg.calibration import calibrate, price_quotes
from vg.estimation import fit_mle, moment_estimates

TRUE = VGParams(theta=-0.16, sigma=0.13, nu=0.25)
DT = 1.0 / 252.0


def _synthetic_returns(n=8000, mu=0.07, seed=0):
    from vg.process import simulate_terminal

    rng = np.random.default_rng(seed)
    return mu * DT + simulate_terminal(TRUE, DT, n, rng)


def test_moment_estimator_recovers_parameters():
    r = _synthetic_returns(n=60_000, seed=1)
    fit = moment_estimates(r, DT)
    assert fit.success
    assert fit.params.sigma == pytest.approx(TRUE.sigma, rel=0.10)
    assert fit.params.nu == pytest.approx(TRUE.nu, rel=0.30)
    assert fit.params.theta == pytest.approx(TRUE.theta, rel=0.40)


def test_moment_estimator_reproduces_the_sample_moments():
    """Whatever it recovers, the fitted moments must match the sample ones."""
    r = _synthetic_returns(n=20_000, seed=2)
    fit = moment_estimates(r, DT)
    for key in ["var", "skewness", "excess_kurtosis"]:
        assert fit.fitted[key] == pytest.approx(fit.sample[key], rel=1e-4, abs=1e-9)


def test_mle_recovers_parameters_when_the_gamma_shape_is_order_one():
    """MLE is trustworthy when dt/nu is O(1) -- here monthly steps, dt/nu = 1/3."""
    from vg.process import simulate_terminal

    dt = 1.0 / 12.0
    true = VGParams(theta=-0.16, sigma=0.13, nu=0.25)
    rng = np.random.default_rng(21)
    r = 0.07 * dt + simulate_terminal(true, dt, 20_000, rng)

    mle = fit_mle(r, dt)
    assert mle.params.sigma == pytest.approx(true.sigma, rel=0.10)
    assert mle.params.nu == pytest.approx(true.nu, rel=0.25)
    assert mle.params.theta == pytest.approx(true.theta, rel=0.40)


def test_mle_beats_the_moment_estimator_on_its_own_criterion():
    """Whatever it recovers, the MLE must not be dominated on the likelihood."""
    from vg.process import log_density

    r = _synthetic_returns(n=20_000, seed=3)
    mom = moment_estimates(r, DT)
    mle = fit_mle(r, DT)
    ll_mom = float(np.sum(log_density(mom.params, r - mom.mu * DT, DT)))
    assert mle.loglik >= ll_mom - 1e-6


def test_mle_overestimates_nu_at_daily_frequency():
    """Document the pathology rather than hide it.

    At dt/nu ~ 0.02 the VG density has a power singularity at the origin and
    over 60% of a simulated daily sample lands within 1e-8 of the drift.  The
    likelihood is then driven by how sharply a parameter set spikes at the mode
    and prefers a much larger nu than the one that generated the data, while the
    moment estimator is unaffected.  If this test ever starts failing because
    the MLE became accurate here, the module docstring needs updating too.
    """
    r = _synthetic_returns(n=20_000, seed=3)
    assert DT / TRUE.nu < 0.05
    assert np.mean(np.abs(r - 0.07 * DT) < 1e-8) > 0.5

    mom = moment_estimates(r, DT)
    mle = fit_mle(r, DT)

    assert mom.params.nu == pytest.approx(TRUE.nu, rel=0.30)
    assert mle.params.nu > 3.0 * TRUE.nu


def test_estimators_reject_tiny_samples():
    with pytest.raises(ValueError, match="at least 50"):
        moment_estimates(np.zeros(10), DT)


